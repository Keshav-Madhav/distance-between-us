import { chromium } from 'playwright-core'
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--mute-audio', '--use-gl=angle', '--ignore-gpu-blocklist'] })
const page = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage()
await page.goto('http://localhost:4417/?fixed'); await page.waitForFunction('window.__g && window.__g.ready')
const C = (o) => ({ steer: 0, boost: true, burner: false, brake: false, strafe: 0, dodgeL: false, dodgeR: false, ...o })
await page.evaluate(() => { const g = window.__g; g.start(); g.skipCountdown() })
await page.waitForTimeout(300)
await page.evaluate((c) => { const g = window.__g; g.player.noCollide = true; g.setMach(5); g.force(c) }, C({ burner: true }))
await page.waitForTimeout(3500); await page.screenshot({ path: 'shots/burn1.png' })
console.log(await page.evaluate(() => JSON.stringify(window.__g.stats())))
await page.evaluate((c) => window.__g.force(c), C({ burner: true, steer: 1 }))
await page.waitForTimeout(900); await page.screenshot({ path: 'shots/burn2.png' })
console.log(await page.evaluate(() => { const s = window.__g.stats(); return `mach ${s.mach} yaw ${s.yaw}` }))
await browser.close()
