import { chromium } from 'playwright-core'
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--mute-audio', '--use-gl=angle', '--ignore-gpu-blocklist'] })
const page = await (await browser.newContext({ viewport: { width: 1280, height: 720 } })).newPage()
await page.goto('http://localhost:4417/?fixed'); await page.waitForFunction('window.__g && window.__g.ready')
const C = (o) => ({ steer: 0, boost: false, brake: false, strafe: 0, dodgeL: false, dodgeR: false, ...o })
await page.evaluate(() => { const g = window.__g; g.start(); g.skipCountdown() })
await page.waitForTimeout(400)
await page.evaluate(() => { const g = window.__g; const c = g.course.cps[1]; g.player.reset(c.x, c.z, Math.atan2(c.tx, c.tz), 4.2); g.player.noCollide = true })
await page.evaluate((c) => window.__g.force(c), C({ steer: 1, brake: true }))
await page.waitForTimeout(1300); await page.screenshot({ path: 'shots/d-drift.png' })
await page.waitForTimeout(500); await page.screenshot({ path: 'shots/d-drift2.png' })
await page.evaluate((c) => window.__g.force(c), C({ steer: -0.5 }))
await page.waitForTimeout(650); await page.screenshot({ path: 'shots/d-boost.png' })
await page.evaluate((c) => window.__g.force(c), C({ boost: true }))
await page.waitForTimeout(1500)
await page.evaluate(() => { const p = window.__g.player; p.slip = 1.3; p.startSpin(true) })
await page.waitForTimeout(350); await page.screenshot({ path: 'shots/d-flip.png' })
await browser.close()
